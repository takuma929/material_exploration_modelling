function s = stat_name(k)
% STAT_NAME  Readable name of a statistic column, e.g. 'rms_contrast_mean' -> 'RMS contrast, mean'.
base = containers.Map( ...
    {'area', 'Y_mean', 'Y_sd', 'Y_med', 'Y_max', 'Y_skew', 'Y_kurt', 'rms_contrast', 'hl_frac', 'hl_contrast', 'edge_energy', ...
     'dark_frac', 'chroma_mean', 'chroma_sd', 'diff_energy', 'bg_Y_mean', 'bg_Y_sd', 'bg_Y_max', 'bg_rms_contrast', 'bg_chroma_mean', ...
     'obj_bg_lum_ratio', 'obj_bg_contrast_ratio', 'obj_bg_max_ratio', 'obj_bg_chroma_ratio', ...
     'coverage', 'coverage_change', 'div_frac', 'div_mean_abs', 'sfm_inlier_ratio', 'flow_speed'}, ...
    {'Object area', 'Mean luminance', 'Luminance SD', 'Median luminance', 'Maximum luminance', 'Luminance skewness', 'Luminance kurtosis', ...
     'RMS contrast', 'Highlight coverage', 'Highlight contrast', 'Edge energy', 'Dark fraction', 'Chroma mean', 'Chroma SD', 'Frame difference', ...
     'Surround luminance', 'Surround luminance SD', 'Surround maximum luminance', 'Surround RMS contrast', 'Surround chroma', ...
     'Object/surround luminance', 'Object/surround contrast', 'Object/surround maximum', 'Object/surround chroma', ...
     'Flow coverage', 'Flow coverage change', 'Flow divergence (fraction)', 'Flow divergence (mean)', 'Flow 3-D reliability', 'Flow speed'});
summ = containers.Map({'mean', 'sd', 'max', 'late_minus_early', 'ac1'}, {'mean', 'SD', 'max', 'late minus early', 'autocorrelation'});
k = char(k);
for key = keys(summ)
    suf = ['_' key{1}];
    if endsWith(k, suf)
        b = k(1:end - numel(suf));
        if isKey(base, b), s = sprintf('%s, %s', base(b), summ(key{1})); return; end
    end
end
s = strrep(k, '_', ' ');
end
